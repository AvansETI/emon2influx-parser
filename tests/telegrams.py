def with_crc(lines: list[str]) -> str:
    body = "\r\n".join(lines) + "\r\n!"
    return f"{body}{crc16(body.encode('latin-1')):04X}\r\n"


def without_crc(lines: list[str]) -> str:
    return "\r\n".join(lines) + "\r\n!\r\n"


